// Pure bootstrap decisions. The CLI reads assets and applies this fixed install manifest.
export type Stack = "ts-node";
export type BootstrapArgs =
  | { readonly kind: "help" }
  | { readonly kind: "error"; readonly reason: string }
  | { readonly kind: "install"; readonly stack: Stack; readonly target: string };
export type BootstrapFile = { readonly source: string; readonly destination: string };

export function parseBootstrapArgs(args: readonly string[]): BootstrapArgs {
  if (args.length === 1 && args[0] === "--help") return { kind: "help" };
  const options = new Map<string, string>();
  for (let i = 0; i < args.length; i += 2) {
    const key = args[i];
    const value = args[i + 1];
    if ((key !== "--stack" && key !== "--target") || !value?.trim() || value.startsWith("--") || options.has(key)) {
      return { kind: "error", reason: "Expected --stack <stack> --target <directory>, with no duplicate or unknown options." };
    }
    options.set(key, value);
  }
  const stack = options.get("--stack");
  const target = options.get("--target");
  if (stack !== "ts-node" || !target) {
    return { kind: "error", reason: "Required: --stack ts-node --target <directory>. Only TypeScript/Node is supported." };
  }
  return { kind: "install", stack, target };
}

export function harnessResources(harnessRoot: string): { extensions: string[]; skills: string[] } {
  return {
    extensions: ["solo-sota-harness", "plan-quint-qa-modes", "self-ratchet"]
      .map(extension => `${harnessRoot}/extensions/${extension}.ts`),
    skills: [`${harnessRoot}/skills`],
  };
}

export function bootstrapFiles(): BootstrapFile[] {
  const shared = ["core/AGENTS.base.md", "spec/scripts/check.sh", "spec/scripts/prove.sh", "overlays/ts-node/OVERLAY.md"];
  return [
    ...shared.map(source => ({ source, destination: source })),
    { source: "core/ARCHITECTURE.template.md", destination: "ARCHITECTURE.md" },
    { source: "overlays/ts-node/lint-architecture.mjs", destination: "scripts/lint-architecture.mjs" },
    { source: "LICENSE", destination: "core/SOLO-SOTA-LICENSE" },
  ];
}

function overlayCommand(overlay: string, label: string): string {
  const line = overlay.split("\n").find(line => line.startsWith(`- **${label}:**`));
  const command = line?.match(/`([^`]+)`/)?.[1];
  if (!command) throw new Error(`Overlay Golden Commands missing ${label}.`);
  return command;
}

export function renderAgents(core: string, overlay: string): string {
  return core.replaceAll("<STACK_CHECK_FAST_CMD>", overlayCommand(overlay, "Fast Check"))
    .replaceAll("<STACK_SCOPED_TEST_CMD>", overlayCommand(overlay, "Scoped Module Test")).trimEnd() +
    "\n\n" + overlay.trimEnd() + "\n";
}

export function renderInit(): string {
  return `#!/usr/bin/env bash
# Generated by apply-harness; install the stack toolchain and Quint before running.
set -euo pipefail
cd "$(dirname "\${BASH_SOURCE[0]}")"
export PATH="$PWD/node_modules/.bin:$PATH"
export AGENT_ID="\${AGENT_ID:-\${PI_AGENT_ID:-default}}"
tsc --noEmit
vitest run --outputFile=".tmp/test-$AGENT_ID.json"
node ./scripts/lint-architecture.mjs
bash ./spec/scripts/check.sh
`;
}

